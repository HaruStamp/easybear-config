#!/usr/bin/env python3
"""showhow v35 — "ถุงมือ" ในกฎความต่อเนื่อง = ระบุชนิดโดยไม่ระบุเงื่อนไข ⇒ โมเดลเติมให้ครบทุกช่อง

หลักฐาน (2026-09-22 · use case "จัดตู้เสื้อผ้ารกให้เป็นระเบียบ" · ไม่ใช่งานสกปรก):
  บอร์ดทั้ง 10 ช่อง + วิดีโอทั้ง 2 ช่วง วาดมือ **ใส่ถุงมือยางขาว** ตลอด ทั้งที่ไม่มีใครสั่งให้ใส่
  ต้นทาง = กฎความต่อเนื่องเขียนว่า `เสื้อผ้าและถุงมือของคนทำ (ชุดเดิมสีเดิม)` — เจตนาคือ "ถ้ามี ให้คงเดิม"

บทเรียนกลาง (ทีม minimal ยืนยันว่าเคยเจอรูปแบบเดียวกันกับกฎเพศเสียง 2026-09-06):
  **"ต้องใช้ X เท่านั้น" = โมเดลตีเป็น "ต้องมี X ทุกที่"**
  ⇒ กฎที่ระบุ *ชนิด* ต้องมาคู่กับกฎที่ระบุ *เงื่อนไขว่ามีหรือไม่มี* เสมอ

🪤 กับดักตอนผ่อนกฎ (บทเรียนของ minimal): ห้ามถอด "ตัวล็อกความต่อเนื่อง" ออกไปด้วย
   ⇒ วลี `(ชุดเดิมสีเดิม)` ต้องอยู่ครบ — ผ่อนแค่ "มีหรือไม่มี" ไม่ใช่ปลดล็อก "ต้องเหมือนเดิม"
🪤 ประโยคนี้อยู่ใน prompt ที่ **ถูก clamp 3,900** (mnBoard2-6 · mnVideo1-6) ⇒ เพิ่มความยาวให้น้อยที่สุด (+3 ตัวอักษร · headroom วัดจริงก่อนแก้: board 56 · video 32 ⇒ ห้ามเกินนี้)
   และต้องวัดซ้ำด้วย scripts/prompt-clamp-real.py ก่อน push
"""
import json, pathlib

P = pathlib.Path(__file__).resolve().parent.parent / 'showhow-dev.json'
raw = P.read_text(encoding='utf-8')

OLD = 'เสื้อผ้าและถุงมือของคนทำ (ชุดเดิมสีเดิม)'
NEW = 'เสื้อผ้าของคนทำ ถุงมือถ้ามี (ชุดเดิมสีเดิม)'

n = raw.count(OLD)
assert n == 6, f'เจอประโยคเดิม {n} จุด (คาด 6 = board2-6 + video) — หยุด'
assert 'ชุดเดิมสีเดิม' in NEW, 'ตัวล็อกความต่อเนื่องหาย'

d = json.loads(raw.replace(OLD, NEW))
P.write_text(json.dumps(d, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
print(f'patched {n} จุด · +{len(NEW)-len(OLD)} ตัวอักษรต่อ prompt')
