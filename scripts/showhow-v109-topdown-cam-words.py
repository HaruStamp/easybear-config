#!/usr/bin/env python3
"""showhow-v109 — มุมกล้อง "มองจากด้านบน" หลุดเป็นมุมหน้าตรง 2-3 ใน 5 ฉาก (ผลิตจริงคืน 2026-09-24 เคส A1)

สาเหตุ 2 ชั้น:
① วิดีโอ: บทเขียน camN = "โคลสอัพท็อปดาวน์" · ตารางวลีกล้องเช็ค "โคลสอัพ" ก่อน "ท็อปดาวน์" (เจอคำแรกก่อนชนะ)
   ⇒ ได้ "tight close-up on the work" · มุมบนหาย
② บอร์ด: ได้ "มุมกล้อง: ท็อปดาวน์นิ่ง" (ทับศัพท์ไทย) · โมเดลภาพไม่เข้าใจ ⇒ วาดมุมหน้าตรงเห็นผ้ากันเปื้อน แล้ววิดีโอลอกตาม
แก้ที่กฎบท (camPlan · mnPlan ไม่โดนตัด ⇒ ไม่แตะเพดานบอร์ด/วิดีโอ):
   camN ทุกฉากขึ้นต้นด้วยคำอังกฤษ "top-down" · ห้ามคำ โคลสอัพ/มาโคร/close-up/macro (ใช้ "top-down ใกล้" แทน)
   · s*th/s*en ระบุว่ามองจากด้านบน
ใช้: python3 scripts/showhow-v109-topdown-cam-words.py
"""
import json
P = 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))
K = 'มองจากด้านบน'
old = c['lookups']['camPlan'][K]
assert old.startswith('มุมกล้องหลัก: มองจากด้านบนลงมาตรง ๆ')
c['lookups']['camPlan'][K] = (
    'มุมกล้องหลัก: มองจากด้านบนลงมาตรง ๆ เห็นพื้นโต๊ะ/พื้นที่ทำงานกับมือที่กำลังทำ ห้ามเห็นหน้าหรือลำตัวด้านหน้า — '
    'camN ทุกฉากต้องขึ้นต้นด้วยคำอังกฤษ "top-down" เช่น "top-down นิ่ง" · "top-down ใกล้" · "top-down ถอยกว้าง" '
    'ห้ามใช้คำ โคลสอัพ มาโคร close-up macro (จะทำให้มุมบนหาย) · s*th และ s*en ทุกฉากระบุว่ามองจากด้านบน '
    '· ฉากปิดถอยกว้างเห็นผลงานได้แต่ยังมองจากด้านบน · เหมาะกับงานบนโต๊ะ ทำอาหาร งานฝีมือ จัดของ')
# ยาม: คำที่ต้องมี + ตารางวิดีโอจับ "top-down" ได้จริงเมื่อไม่มีคำโคลสอัพนำหน้า
t = c['lookups']['camPlan'][K]
assert '"top-down"' in t and 'ห้ามใช้คำ โคลสอัพ' in t
print('camPlan[มองจากด้านบน] ใหม่', len(t), 'ตัวอักษร (เดิม', len(old), ') · mnPlan ไม่โดนตัด')
json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
