#!/usr/bin/env python3
# showhow v54 — เขียนกฎถุงมือของ v53 ใหม่ให้ตรงกับ "อาการจริง" ไม่ใช่ห้ามแบบเหมารวม
#
# v53 เขียนว่า "ห้ามเปลี่ยนจากมือเปล่าเป็นใส่ถุงมือกลางคลิป"
# ยิงจริงที่ 60 วิ แล้ว LLM เขียน: ฉาก 7 มือเปล่าวางฟองน้ำ · ฉาก 9 **ใส่ถุงมือให้ดู** · ฉาก 13 ถุงมือขัดเตา
#   ⇒ ผิดตัวอักษรของกฎ แต่ "เล่าเรื่องถูก" — การใส่ถุงมือเป็นขั้นเตรียมงานที่คนดูรับได้
#   ⇒ ของจริงที่พังคือคลิปล้างแอร์: มือเปล่าเปิดฝา/จับของสกปรก แล้ว **จู่ ๆ ก็มีถุงมือ** โดยไม่มีฉากใส่
# ⇒ กฎที่ถูกคือ "ถ้าจะมีถุงมือ ต้องมีมาแต่แรก **หรือ** มีฉากใส่ถุงมือก่อนมือแตะงานสกปรก" — ห้ามโผล่มาเอง
import json, sys

P = sys.argv[1] if len(sys.argv) > 1 else 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))
s = c['brain']['mn']['sys']

OLD = ('\n- คนทำแต่งตัวชุดเดียวกันทั้งคลิป และ **ถุงมือต้องมีหรือไม่มีเหมือนกันทุกฉากตั้งแต่ฉากแรกที่เห็นมือ** — '
       'งานที่ควรใส่ถุงมือ (ล้าง ขัด น้ำยา สารเคมี ฝุ่นหนา) ให้ใส่ตั้งแต่ฉากแรก ห้ามเปลี่ยนจากมือเปล่าเป็นใส่ถุงมือกลางคลิป และห้ามถอดกลับ')
NEW = ('\n- คนทำแต่งตัวชุดเดียวกันทั้งคลิป · **ถุงมือห้ามโผล่มาเอง**: ถ้าคลิปนี้จะมีถุงมือ ต้องเลือกอย่างใดอย่างหนึ่ง — '
       'ใส่มาตั้งแต่ฉากแรกที่เห็นมือ **หรือ** มีฉากที่เห็นการใส่ถุงมือ ก่อนฉากแรกที่มือแตะงานสกปรก · '
       'เมื่อใส่แล้วต้องใส่ต่อจนจบ สีเดิม ห้ามถอดกลับเป็นมือเปล่า')
assert s.count(OLD) == 1, 'ไม่เจอกฎถุงมือของ v53 (รันสคริปต์ v53 ก่อน)'
c['brain']['mn']['sys'] = s.replace(OLD, NEW)

ops_before = json.dumps(json.load(open(P, encoding='utf-8'))['ops'], ensure_ascii=False)
assert json.dumps(c['ops'], ensure_ascii=False) == ops_before, 'v54 ต้องไม่แตะ ops'
json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(f"v54 ok · brain.mn.sys {len(s)} → {len(c['brain']['mn']['sys'])}")
