#!/usr/bin/env python3
"""showhow v43 — โหมด "ไม่มีคน" ต้องเขียนบทเป็น **สภาพที่เปลี่ยนไป** ไม่ใช่ **สิ่งของเป็นผู้ลงมือ**

หลักฐาน (2026-09-22 · เคสล้างแอร์ 50 วิ · โหมด `ไม่มีคน` · บอร์ดช่วง 4 วาด 2 รอบ):
  บท (mnPlan ทำถูกตามกฎ ไม่มีคำว่าคน/มือเลย):
    ฉาก 16 "ผ้าสะอาดค่อยๆ เช็ดคราบน้ำออกจากขอบตัวเครื่อง"   ← ผ้าเป็นผู้กระทำ
    ฉาก 17 "แผ่นกรองสะอาดใบแรกเลื่อนกลับเข้าที่เดิม"        ← แผ่นกรองเป็นผู้กระทำ
  บอร์ดทั้ง 2 รอบ **เติมมือคนเข้ามาถือผ้า** ทั้งที่ prompt เขียนชัดว่า "ห้ามมีคนหรือมือในทุกช่อง"

ราก = **ถ้อยคำของเราเองในกฎ `charPlan` สั่งให้เขียนแบบนั้น**: "ของและพื้นที่เปลี่ยนไปเองทีละขั้น (**ของขยับเข้าที่**…)"
  ⇒ LLM เขียนประโยคที่สิ่งของเป็นประธานของกริยาที่ต้องใช้มือ · โมเดลวาดภาพเจอ "ผ้ากำลังเช็ด" ก็เติมมือให้ เพราะผ้าลอยเช็ดเองไม่สมเหตุสมผล
  (ตรงกับกฎเหล็กข้อ "เลี่ยงของที่ AI พัง — ของลอย" ที่เรามีอยู่แล้วแต่ไม่ได้ผูกกับโหมดนี้)

แก้ที่ชั้นวางแผน ไม่ใช่ชั้นวาด: เขียนเป็นสภาพ ณ ช็อตนั้น (ก่อน → ระหว่าง → หลัง) ห้ามให้สิ่งของเป็นผู้กระทำงานที่ต้องใช้มือ
"""
import json, pathlib

P = pathlib.Path(__file__).resolve().parent.parent / 'showhow-dev.json'
d = json.loads(P.read_text(encoding='utf-8'))
lk = d['lookups']['charPlan']

OLD = ('กฎคนในคลิป: ไม่มีคนและไม่มีมือเลยทุกฉาก — ของและพื้นที่เปลี่ยนไปเองทีละขั้นแบบไทม์แลปส์ '
       '(ของขยับเข้าที่ คราบจางหาย สีค่อย ๆ ขึ้น) · เขียน s*th/s*en ให้ไม่มีบุคคล')
NEW = ('กฎคนในคลิป: ไม่มีคนและไม่มีมือเลยทุกฉาก — เขียนแต่ละฉากเป็น **สภาพของพื้นที่/ของ ณ ช็อตนั้น** '
       '(คราบจางลงครึ่งหนึ่ง · แผ่นกรองสะอาดอยู่ในตำแหน่งแล้ว · พื้นแห้งเงา) '
       '🔴 **ห้ามเขียนให้สิ่งของเป็นผู้ลงมือทำงานที่ต้องใช้มือ** (ผ้ากำลังเช็ด · แผ่นกรองเลื่อนเข้าที่ · แปรงกำลังขัด) '
       'เพราะภาพจะเติมมือคนเข้ามาถือของนั้นให้สมเหตุสมผล · เล่าความคืบหน้าด้วยการเทียบสภาพระหว่างช็อต ไม่ใช่ด้วยการกระทำ')

n = sum(1 for v in lk.values() if v == OLD)
assert n == 2, f'เจอถ้อยคำเดิม {n} คีย์ (คาด 2 = ไม่มีคน × 2 แหล่งภาพหน้า) — หยุด'
for k, v in list(lk.items()):
    if v == OLD: lk[k] = NEW
assert sum(1 for v in lk.values() if v == NEW) == 2

P.write_text(json.dumps(d, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
print(f'แก้ charPlan โหมด "ไม่มีคน" {n} คีย์ · +{len(NEW)-len(OLD)} ตัวอักษร (อยู่ใน systemInstruction ไม่ชน clamp)')
