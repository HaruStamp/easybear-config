import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); P = os.path.join(HERE, '..', 'showhow-dev.json')
V18B = ('สินค้า = ของจริงตามรูปที่แนบ (หลายชิ้น = ชิ้นละรูป): **ทุกช่องต้องเก็บทรง สี ฉลาก โลโก้ สัดส่วน จำนวน และด้าม/ความยาวด้าม/สีขนแปรง ตามรูปให้เป๊ะ ในรูปมีด้ามยาวต้องมีด้ามยาว ห้ามย่อเป็นแปรงมือ** · มุมที่รูปไม่มีให้ใช้มุมใกล้สุด · รูปเป็นแพ็กหลายชิ้นหรือมีป้ายโปรโมชันทับ ให้วาดชิ้นเดียว คงฉลากและสีเดิม เอาออกเฉพาะป้ายโปรโมชันกับพลาสติกหุ้ม (ห้ามเปลี่ยนทรง) · ห้ามลอกฉากหลังหรือของประกอบจากรูป · **ช่องไหนมีสินค้าในเฟรม ต้องเป็นสินค้าตามรูปเท่านั้น ห้ามคิดขวด กล่อง แปรง หรือแบรนด์อื่นขึ้นมาเองแม้บทช่องนั้นไม่ได้พูดถึง**')
V17 = ('สินค้า = ของจริงตามรูปที่แนบ (หลายชิ้น = ชิ้นละรูป): ห้ามเปลี่ยนสี ทรง สัดส่วน ฉลาก โลโก้ จำนวน ห้ามวาดใหม่หรือเป็นการ์ตูน · มุมที่รูปไม่มีให้ใช้มุมใกล้สุด · **เก็บรูปทรง สีตัวขวด/ด้าม ฉลาก โลโก้ และสัดส่วนตามรูปให้เป๊ะ** ถ้ารูปเป็นแพ็กหลายชิ้นหรือมีป้ายโปรโมชันทับ ให้วาดชิ้นเดียวโดยคงฉลากและสีเดิม เอาเฉพาะป้ายโปรโมชันกับพลาสติกหุ้มออก (ห้ามเปลี่ยนเป็นขวดหรือแปรงทรงอื่น)'
       ' · **ด้ามยาวในรูปต้องยาวเท่ารูปทุกช่อง ห้ามย่อเป็นแปรงมือ · สีขนแปรงตามรูป**'
       ' · ห้ามลอกฉากหลังหรือของประกอบจากรูป · **ช่องไหนมีสินค้าอยู่ในเฟรม ต้องเป็นสินค้าตามรูปที่แนบเท่านั้น ห้ามคิดขวด กล่อง แปรง หรือแบรนด์อื่นขึ้นมาเองแม้บทช่องนั้นไม่ได้พูดถึงสินค้า**')
TRIM = [  # (เดิม, ใหม่) — คำซ้ำนอกบรรทัดสินค้า
    (' · วางช่องติดกันสนิทไม่มีขอบขาวเหมือนกัน แต่ห้ามลอกภาพในช่อง', ' · ห้ามลอกภาพในช่อง'),
    ('ห้ามเป็นภาพวาด การ์ตูน เวกเตอร์ ภาพประกอบ หรือ 3D เรนเดอร์ ห้ามมีเส้นเอฟเฟกต์การเคลื่อนไหวหรือคำเอฟเฟกต์',
     'ห้ามเป็นภาพวาด การ์ตูน เวกเตอร์ หรือ 3D เรนเดอร์ ห้ามมีเส้นเอฟเฟกต์หรือคำเอฟเฟกต์'),
    ('· นอกจากนี้ห้ามพิมพ์ตัวหนังสือใด ๆ ลงบนแผ่น ทั้งภาษาไทยและอังกฤษ ชื่อสไตล์ แบรนด์ที่ไม่ได้แนบ หรือ emoji',
     '· ห้ามพิมพ์ตัวหนังสืออื่นบนแผ่น ทั้งไทยและอังกฤษ ชื่อสไตล์ แบรนด์ที่ไม่ได้แนบ หรือ emoji'),
]
raw = open(P, encoding='utf-8').read()
s = json.dumps(json.loads(raw), ensure_ascii=False)
n = s.count(V18B); assert n == 6, f'บรรทัดสินค้า v18b {n} จุด (คาด 6)'
s = s.replace(V18B, V17)
for old, new in TRIM:
    c = s.count(old); assert c >= 6, (old[:30], c); s = s.replace(old, new)
    print(f'  ตัด "{old[:24]}…" {c} จุด · -{len(old)-len(new)} ตัวอักษร/ครั้ง')
