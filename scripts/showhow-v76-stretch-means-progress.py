#!/usr/bin/env python3
# showhow v76 — บอกให้ชัดว่า "ยืดองก์" แปลว่าอะไร (2026-09-22 ดึกมาก)
#
# 🔎 ทำไมกฎ v74 ไม่ได้ผล — ไม่ใช่เพราะ LLM ดื้อ แต่เพราะ **config ขัดกันเอง แล้วกฎใหม่แพ้**
#   lenSys[40] : "องก์ 4 ฉาก = ยืดจังหวะเดียวกันออก ไม่ใช่เรื่องใหม่"
#   arcPlan    : "ฉาก 5 ผลลัพธ์ในมุมกล้องเดียวกับฉาก 1"
#   ⇒ องก์ 5 (ฉาก 17-20 ที่ 40 วิ) = "ผลลัพธ์" ยืดออก 4 ฉาก = ภาพนิ่งผลลัพธ์ 4 ใบติดกัน
#   v74 บอก "ภาพนิ่งผลลัพธ์ช่วงละไม่เกิน 1 ฉาก" ซึ่งขัดกับ 2 บรรทัดบน — LLM ตามโครงเรื่อง กฎใหม่จึงแพ้
#   วัดจริง 2 รอบติด (regress40 · v75-regress40): องก์ 5 ได้ภาพนิ่ง 3 ฉากติดทั้งสองรอบ
#
# ⇒ แก้ที่ต้นเรื่อง: คำว่า "ยืด" เราไม่เคยนิยาม โมเดลเลยตีความว่า "ถ่ายของเดิมซ้ำหลายมุม"
#   นิยามใหม่: ยืด = เล่า **ความคืบหน้าทีละขั้นของจังหวะนั้น** · แม้แต่องก์ผลลัพธ์ก็ต้องมีคนทำอะไรอยู่
#   แล้วปิดด้วยภาพกว้างผลลัพธ์ **ฉากเดียว** คือฉากสุดท้ายของคลิป
# 🪤 บทเรียน: ก่อนเพิ่มกฎใหม่ ต้องหาก่อนว่ามีบรรทัดไหนใน config สั่งตรงข้ามอยู่หรือเปล่า
#    ไม่งั้นได้กฎที่ขัดกันเอง แล้วเราจะสรุปผิดว่า "โมเดลไม่ฟัง"
import json, sys

P = sys.argv[1] if len(sys.argv) > 1 else 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))
t = c['lookups']['lenSys']

TAIL = ('ยืดจังหวะเดียวกันออก ไม่ใช่เรื่องใหม่ — "ยืด" คือเล่าความคืบหน้าของจังหวะนั้นทีละขั้น '
        'ไม่ใช่ถ่ายของเดิมซ้ำหลายมุม · แม้แต่องก์ผลลัพธ์ก็ต้องมีคนกำลังทำอะไรอยู่ในเฟรม '
        '(เก็บของ เช็ดรอบสุดท้าย วางของกลับที่ เปิดใช้งานจริง) แล้วปิดด้วยภาพกว้างผลลัพธ์ '
        'ฉากเดียวคือฉากสุดท้ายของคลิป')

hit = []
for k, v in t.items():
    if 'ยืดจังหวะเดียวกันออก ไม่ใช่เรื่องใหม่' not in v:
        continue                      # 10 วิ = องก์ละ 1 ฉาก ไม่มีประโยคนี้
    assert '"ยืด" คือเล่าความคืบหน้า' not in v, 'รันซ้ำ'
    t[k] = v.replace('ยืดจังหวะเดียวกันออก ไม่ใช่เรื่องใหม่', TAIL, 1)
    hit.append((k, len(t[k]) - len(v)))

assert len(hit) == 5, hit      # 20·30·40·50·60 (10 วิ ไม่มี)
json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('v76 ok · แก้ lenSys', hit)
