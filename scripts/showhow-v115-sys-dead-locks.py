#!/usr/bin/env python3
"""showhow-v115 — ตัดกฎบทที่อ้างถึง "มุมกล้อง/การนำเสนอรายฉากที่ผู้ใช้ล็อก" ซึ่งไม่มีแล้วตั้งแต่ v82 (minimal ทักจากตอนทำตามมาตรฐานเรา 2026-09-25)
brain.mn.sys ยังมี 3 ท่อนสั่ง AI ให้ "ทำตามค่าที่ผู้ใช้ล็อก" ทั้งที่ช่อง svCam1-5/svPres1-5 ถูกตัดไปแล้ว (ไม่มีใครส่งค่ามา = ข้อความตาย สับสน LLM)
+ ตัวอย่าง camN "ท็อปดาวน์" (ทับศัพท์ไทย) → "top-down ใกล้" ตามบทเรียน v109 (บอร์ดไม่เข้าใจทับศัพท์)
mnPlan ไม่โดนตัด ⇒ ไม่แตะเพดานบอร์ด/วิดีโอ
ใช้: python3 scripts/showhow-v115-sys-dead-locks.py
"""
import json
P = 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))
s = c['brain']['mn']['sys']
R = [
 ('\n\nข้อกำหนดรายฉากจากผู้ใช้ (มุมกล้อง / การนำเสนอ): ถ้าผู้ใช้ระบุมา ต้องทำตามอย่างเคร่งครัดทุกคลิป และสะท้อนให้เห็นจริงใน s*th กับ s*en · ค่าว่าง = ออกแบบเองให้เหมาะกับงาน', ''),
 (' (ยกเว้นฉากที่ผู้ใช้ล็อกมุมกล้อง/การนำเสนอไว้ ให้ทำตามที่ล็อกทุกคลิป แล้วสร้างความต่างจากรายละเอียดอื่น)', ''),
 (' — ฉากที่ผู้ใช้ล็อกมุมกล้องไว้ camN ต้องตรงกับที่ล็อกทุกคลิป ฉากที่ไม่ล็อกให้เลือกเองตามจังหวะเรื่อง', ' — เลือกเองตามจังหวะเรื่อง (ถ้ามีกฎมุมกล้องหลัก ให้ทำตามกฎนั้น)'),
 ('"ท็อปดาวน์" "โคลสอัพช้าๆ"', '"top-down ใกล้" "โคลสอัพช้าๆ"'),
]
for a, b in R:
    assert s.count(a) == 1, a[:40]
    s = s.replace(a, b)
assert 'ผู้ใช้ล็อก' not in s and 'ข้อกำหนดรายฉากจากผู้ใช้' not in s and 'ท็อปดาวน์' not in s
c['brain']['mn']['sys'] = s
print('ตัดกฎตาย 3 ท่อน + เปลี่ยนตัวอย่าง camN · sys', len(s), 'ตัวอักษร')
json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
