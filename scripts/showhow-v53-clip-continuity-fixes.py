#!/usr/bin/env python3
# showhow v53 — เก็บ 3 อาการที่เจอจากคลิปจริงคืน 2026-09-22
#
# ① ถุงมือโผล่กลางคลิป (คลิปล้างแอร์ 50 วิ: วิ 3-8 มือเปล่า · วิ 11+ ใส่ถุงมือฟ้า)
#    ราก: กฎต่อเนื่องเขียนว่า "ถุงมือถ้ามี (ชุดเดิมสีเดิม)" = บังคับว่าถ้ามีต้องสีเดิม
#         แต่ไม่ได้บังคับว่า "ถ้าจะมี ต้องมีตั้งแต่ฉากแรกที่เห็นมือ"
# ② สีชิ้นส่วนเล็กของสินค้าเพี้ยนเฉพาะชั้นวิดีโอ (กล่องเก็บของ: รูปจริง+บอร์ด หูหิ้วน้ำเงิน → วิดีโอเทา/ดำ)
#    ราก: PRODUCT LOCK บอก "ห้ามเปลี่ยนสี" อยู่แล้ว แต่ s*en ไม่ได้พูดถึงสีชิ้นส่วน
#         ⇒ โมเดลวิดีโอมีแต่คำสั่งห้าม ไม่มีคำบรรยายให้ยึด
# ③ หัวเรื่องโหมด "ค้างทั้งคลิป" ตัดบรรทัด/ขนาดไม่เหมือนกันข้ามช่วง (คลิปพัดลม 20 วิ)
#    ราก: ov1 ยาว 29 ตัวอักษร ⇒ โมเดลตัดเป็น 2 บรรทัดเอง และตัดคนละที่ในแต่ละช่วง
#         (prompt สั่ง "one line ... same size and position" อยู่แล้ว — สั่งไม่ได้เพราะข้อความไม่พอดีบรรทัด)
#
# 🔑 ทั้ง 3 ข้อแก้ที่ **บทของ LLM** (`brain.mn.sys` + `textPlan`) ซึ่งอยู่ใน systemInstruction ของ mnPlan
#    = ไม่ผ่าน execLeaf จึง **ไม่กินเพดาน 3,900** ของ prompt บอร์ด/วิดีโอเลยสักตัวอักษร
#    (headroom บอร์ดเหลือ 47 · วิดีโอ 98 — เติมข้อความใน prompt พวกนั้นไม่ได้แล้ว)
import json, sys

P = sys.argv[1] if len(sys.argv) > 1 else 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))
sysmn = c['brain']['mn']['sys']
before = len(sysmn)

# ① ถุงมือ/ชุด — ต่อท้ายกฎ "ต่อเนื่องจริง"
ANCHOR1 = '- ต่อเนื่องจริง: ของที่วางหรือทำไปแล้วในฉากก่อน ต้องยังอยู่ในฉากถัดไป ห้ามหายไปเอง'
ADD1 = ('\n- คนทำแต่งตัวชุดเดียวกันทั้งคลิป และ **ถุงมือต้องมีหรือไม่มีเหมือนกันทุกฉากตั้งแต่ฉากแรกที่เห็นมือ** — '
        'งานที่ควรใส่ถุงมือ (ล้าง ขัด น้ำยา สารเคมี ฝุ่นหนา) ให้ใส่ตั้งแต่ฉากแรก ห้ามเปลี่ยนจากมือเปล่าเป็นใส่ถุงมือกลางคลิป และห้ามถอดกลับ')
assert sysmn.count(ANCHOR1) == 1, 'ไม่เจอกฎ "ต่อเนื่องจริง" (โครงเปลี่ยน — หยุด)'
assert 'ถุงมือต้องมีหรือไม่มีเหมือนกันทุกฉาก' not in sysmn, 'รันซ้ำ'
sysmn = sysmn.replace(ANCHOR1, ANCHOR1 + ADD1)

# ② สีชิ้นส่วนเด่นของสินค้าต้องอยู่ใน s*en
ANCHOR2 = '- ใช้เฉพาะข้อมูลที่ผู้ใช้ให้มา ห้ามแต่งข้อเท็จจริงเพิ่มเอง'
ADD2 = ('- ฉากไหนเห็นสินค้า ให้เขียน **สีและชิ้นส่วนเด่น** ของมันลงใน s*en ด้วย (เช่น หูหิ้วสีน้ำเงิน ฝาใส ปุ่มแดง ด้ามยาวสีเทา ขนแปรงขาว) '
        'ตามรูปจริง — ไม่เขียนไว้ โมเดลวิดีโอจะเปลี่ยนสีชิ้นส่วนเล็กเอาเองแม้รูปสินค้าจะแนบไปด้วย\n')
assert sysmn.count(ANCHOR2) == 1, 'ไม่เจอกฎ "ใช้เฉพาะข้อมูลที่ผู้ใช้ให้มา"'
assert 'สีและชิ้นส่วนเด่น' not in sysmn, 'รันซ้ำ'
sysmn = sysmn.replace(ANCHOR2, ADD2 + ANCHOR2)
c['brain']['mn']['sys'] = sysmn

# ③ ov1 ของโหมดหัวเรื่อง ต้องพอดี 1 บรรทัด
tp = c['lookups']['textPlan']
LIMIT = ' · **ov1 ยาวไม่เกิน 20 ตัวอักษรไทย** (นับรวมวรรค) เพื่อให้พิมพ์จบในบรรทัดเดียว — ยาวกว่านี้โมเดลจะตัดบรรทัดเอง และตัดคนละที่ในแต่ละช่วง 10 วินาที'
for k in ('หัวเรื่องตอนเปิด', 'หัวเรื่องค้างทั้งคลิป'):
    assert k in tp, k
    assert 'ยาวไม่เกิน 20 ตัวอักษรไทย' not in tp[k], 'รันซ้ำ ' + k
    tp[k] = tp[k] + LIMIT
# โหมดค้างทั้งคลิปมีประโยคเดิมที่หลวมกว่า — แทนด้วยเหตุผลที่ตรงกว่า
OLD = ' · ov1 ต้องสั้นพอที่จะอ่านได้ตลอดคลิปโดยไม่บังงาน'
assert tp['หัวเรื่องค้างทั้งคลิป'].count(OLD) == 1
tp['หัวเรื่องค้างทั้งคลิป'] = tp['หัวเรื่องค้างทั้งคลิป'].replace(OLD, ' · ข้อความนี้ค้างทุกเฟรมทุกช่วง จึงต้องขึ้นเหมือนกันเป๊ะทุกช่วง')

# ไม่มีการแตะ prompt ของ mnBoard*/mnVideo* — ยืนยันด้วยการเทียบไบต์
ops_before = json.dumps(json.load(open(P, encoding='utf-8'))['ops'], ensure_ascii=False)
assert json.dumps(c['ops'], ensure_ascii=False) == ops_before, 'v53 ต้องไม่แตะ ops เลย (เพดาน prompt เหลือน้อย)'

json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(f'v53 ok · brain.mn.sys {before} → {len(sysmn)} (+{len(sysmn)-before}) · textPlan 2 โหมด · ops ไม่ขยับ')
