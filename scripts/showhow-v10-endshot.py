#!/usr/bin/env python3
# showhow-v10-endshot.py — "จบด้วยภาพผลลัพธ์มุมเดียวกับภาพเปิด" (พี่หมีสั่ง 2026-09-20)
# ปัญหาที่เจอจากคลิปจัดสวนจริง: ① ฉากผลลัพธ์ภาพกว้างอยู่ฉาก 9 แล้วยังมีโคลสอัพมุกปิดท้ายต่อ ⇒ คลิปไม่จบที่ภาพเปรียบเทียบ
#                                  ② ฉาก 9 วาดเป็นสวนคนละมุมคนละที่กับฉาก 1 ทั้งที่บทสั่ง "มุมเดียวกับฉากแรก"
# แก้: บทบังคับ ฉากแรก = ภาพกว้างทั้งพื้นที่ · ฉากสุดท้ายของคลิป = ภาพกว้างผลลัพธ์จากจุดยืน/ความสูง/ทิศเดียวกับฉากแรก · มุกปิดเลื่อนไปฉากรองสุดท้าย
# ลำดับการรัน: git show 875efd7~1:showhow-dev.json > showhow-dev.json && python3 scripts/showhow-v9-board-collage.py && python3 scripts/showhow-v10-endshot.py
import json, os
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'showhow-dev.json')
raw = open(P, encoding='utf-8').read(); d = json.loads(raw)
n = 0

# ① กฎเหล็กใน brain.mn.sys
sys_ = d['brain']['mn']['sys']
OLD_SAME = '- ฉากสุดท้ายมุมกล้องเดียวกับฉากแรกเป๊ะ สำหรับโครง ก่อน → ลงมือ → หลัง และ ปัญหา → แก้แล้ว (ทัวร์จุดเด่น หรือของยาวอย่างรั้ว เดินกล้องได้) — ปิดเสียงปิดข้อความแล้วคนดูยังเห็นทันทีว่าก่อนกับหลังต่างกันตรงไหน'
NEW_SAME = ('- เปิดกับปิดต้องเทียบกันได้ (โครง ก่อน → ลงมือ → หลัง และ ปัญหา → แก้แล้ว): **ฉากแรก = ภาพกว้างเห็นทั้งพื้นที่ก่อนทำ** · '
            '**ฉากสุดท้ายของคลิป = ภาพกว้างผลลัพธ์ จุดยืนกล้อง ความสูง ทิศทาง และกรอบภาพเดียวกับฉากแรกเป๊ะ เปลี่ยนเฉพาะสภาพพื้นที่** '
            '(ทัวร์จุดเด่น หรือของยาวอย่างรั้ว เดินกล้องได้) — ปิดเสียงปิดข้อความแล้วคนดูยังเห็นทันทีว่าก่อนกับหลังต่างกันตรงไหน')
assert OLD_SAME in sys_; sys_ = sys_.replace(OLD_SAME, NEW_SAME); n += 1

OLD_JOKE = '- ผู้ใช้ให้ไอเดีย/มุกปิดท้ายมา = ฉากสุดท้ายรับ "การใช้งานแถม" นั้น'
NEW_JOKE = '- ผู้ใช้ให้ไอเดีย/มุกปิดท้ายมา = ฉาก**รองสุดท้าย**รับ "การใช้งานแถม" นั้น แล้วปิดคลิปด้วยภาพกว้างผลลัพธ์เสมอ (ห้ามเอาโคลสอัพมุกปิดไปไว้ฉากสุดท้าย)'
assert OLD_JOKE in sys_; sys_ = sys_.replace(OLD_JOKE, NEW_JOKE); n += 1
d['brain']['mn']['sys'] = sys_

# ② โครงเรื่องแบบ 1 ใน lenSys ทุกความยาว
OLD_ARC = '- ก่อน → ลงมือ → หลัง: ฉาก 1 ก่อน (หรือเปิดด้วยการลงมือ) · 2 เตรียมของ · 3 ลงมือทำ · 4 คืบหน้า · 5 ผลลัพธ์ มุมกล้องเดียวกับฉาก 1'
NEW_ARC = '- ก่อน → ลงมือ → หลัง: ฉาก 1 ก่อน ภาพกว้างเห็นทั้งพื้นที่ · 2 เตรียมของ · 3 ลงมือทำ · 4 คืบหน้า · 5 ผลลัพธ์ ภาพกว้างมุมเดียวกับฉาก 1 (ฉากสุดท้ายสุดของคลิปต้องเป็นภาพนี้)'
for k, v in d['lookups']['lenSys'].items():
    if OLD_ARC in v: d['lookups']['lenSys'][k] = v.replace(OLD_ARC, NEW_ARC); n += 1

open(P, 'w', encoding='utf-8').write(json.dumps(d, ensure_ascii=False, indent=1) + ('\n' if raw.endswith('\n') else ''))
print(f'✓ v10 endshot · แก้ {n} จุด ·', os.path.getsize(P), 'bytes')
