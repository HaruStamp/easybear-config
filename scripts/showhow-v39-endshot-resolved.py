#!/usr/bin/env python3
"""showhow v39 — ฉากสุดท้ายต้องเขียนให้เห็นว่า "ของที่เป็นปัญหาในฉากแรกหายไปแล้ว" ไม่ใช่แค่โชว์ของใหม่

หลักฐาน (2026-09-22 · use case "ติดตั้งชั้นวางติดผนังในห้องนั่งเล่น" 30 วิ):
  ฉาก 1  = ห้องที่มี **ของกองบนพื้น** + ผนังเปล่า
  ฉาก 15 = "Final wide shot matching the framing of scene 1, showing three neat shelves with decor."
  ⇒ บอร์ดวาดถูกตามบท: ชั้นติดผนังสวย **แต่ของยังกองเต็มพื้นเหมือนเดิม** — คนดูไม่รู้สึกว่างานเสร็จ

ราก: กฎเดิมบังคับ "มุมเดียวกับฉากแรก + เปลี่ยนเฉพาะสภาพพื้นที่" และ "ผลลัพธ์ต้องครอบทั้งพื้นที่"
  แต่ไม่มีข้อไหนสั่งว่า **สิ่งที่เป็นปัญหาในฉากแรกต้องหายไปในฉากสุดท้าย และต้องเขียนลงในบท**
  ⇒ LLM เขียนฉากปิดโดยพูดถึงแต่ของใหม่ · โมเดลวาดภาพจึงคง "ของเดิม" ไว้ตามกฎความต่อเนื่อง (ทำถูกทุกฝ่าย แต่ผลรวมผิด)

🪤 ต่อจาก v34 (ผลลัพธ์ต้องไม่ถูกบัง) — คนละอาการ: v34 = ผลลัพธ์ถูกบัง · v39 = ปัญหาเดิมยังอยู่
"""
import json, pathlib

P = pathlib.Path(__file__).resolve().parent.parent / 'showhow-dev.json'
d = json.loads(P.read_text(encoding='utf-8'))
s = d['brain']['mn']['sys']

OLD = 'ผลลัพธ์ต้องเห็นจริงในเฟรม ห้ามถูกบัง (ห้ามปิดประตูตู้ ปิดฝา คลุมผ้า หรือเก็บของที่เป็นผลลัพธ์ออกนอกเฟรม)'
NEW = (OLD + ' · **สิ่งที่เป็นปัญหาในฉากแรก (ของกองรก คราบ ของเสีย พื้นที่ว่างเปล่า) ต้องหายไปแล้วในฉากสุดท้าย '
       'และต้องเขียนลงใน s*th/s*en ของฉากนั้นให้ชัด** — เขียนแค่ของใหม่ที่เพิ่มเข้ามา = ภาพจะคงของเดิมไว้ทั้งหมด งานดูไม่เสร็จ')

assert s.count(OLD) == 1, f'ไม่เจอประโยคของ v34 ({s.count(OLD)} ครั้ง) — รัน v34 ก่อน'
assert NEW not in s, 'แก้ไปแล้ว'
d['brain']['mn']['sys'] = s.replace(OLD, NEW)
P.write_text(json.dumps(d, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
lk = d['lookups']
print('patched +%d ตัวอักษร' % (len(NEW) - len(OLD)))
for sec in ('20', '60'):
    n = len(d['brain']['mn']['sys']) + len(lk['lenSys'][sec]) + len(lk['lenOut'][sec]) + len(lk['lenVo'][sec])
    print(f'  systemInstruction {sec} วิ ≈ {n:,} ตัวอักษร')
