#!/usr/bin/env python3
"""showhow v34 — ฉากปิดต้อง "เห็นผลลัพธ์จริง" ห้ามถูกบัง

ที่มา (เคสจริง 2026-09-22 · use case "จัดตู้เสื้อผ้ารกให้เป็นระเบียบ" 20 วิ):
  บทฉาก 10 = "ภาพกว้างตู้ที่จัดเสร็จแล้ว มุมเดียวกับฉากแรก บานเลื่อนปิดสนิท"
  ⇒ บอร์ดช่องที่ 10 วาดตู้ **ปิดสนิท** — ผลลัพธ์ที่อุตส่าห์ทำมา 9 ฉากมองไม่เห็นเลย
  กฎเดิมบังคับแค่ "มุมเดียวกับฉากแรก + เปลี่ยนเฉพาะสภาพพื้นที่" ⇒ ปิดประตูก็ยังถือว่าทำตามกฎ
  🪤 หลักฐานไม่สุด: วิดีโอรอบนั้น "รอด" เพราะไปตามบท s10en ที่เขียนว่า partially closed (บานเลื่อนเปิดแง้มเห็นของข้างใน)
     ⇒ บอร์ดพังแต่คลิปไม่พัง · แก้ตรงนี้คือกันไม่ให้บทเขียนคำว่า "ปิด" ตั้งแต่ต้นทาง ไม่ใช่กันอาการที่เห็นในคลิป

แก้: ต่อท้ายประโยคฉากสุดท้าย ว่าผลลัพธ์ต้องมองเห็นในเฟรม ห้ามบังด้วยประตู/ฝา/ผ้าคลุม
🪤 ไฟล์นี้แก้ `brain.mn.sys` (systemInstruction ของ mnPlan · ไม่ผ่าน execLeaf จึงไม่ชน clamp 3,900)
   แต่ยังต้องดูเพดาน generate.text — พิมพ์ความยาวใหม่ทุกความยาวคลิปท้ายสคริปต์
"""
import json, sys, pathlib

P = pathlib.Path(__file__).resolve().parent.parent / 'showhow-dev.json'
d = json.loads(P.read_text(encoding='utf-8'))
s = d['brain']['mn']['sys']

OLD = 'ปิดเสียงปิดข้อความแล้วคนดูยังเห็นทันทีว่าก่อนกับหลังต่างกันตรงไหน'
NEW = ('ปิดเสียงปิดข้อความแล้วคนดูยังเห็นทันทีว่าก่อนกับหลังต่างกันตรงไหน — '
       'ผลลัพธ์ต้องเห็นจริงในเฟรม ห้ามถูกบัง (ห้ามปิดประตูตู้ ปิดฝา คลุมผ้า หรือเก็บของที่เป็นผลลัพธ์ออกนอกเฟรม)')

assert s.count(OLD) == 1, f'เจอประโยคเดิม {s.count(OLD)} ครั้ง — หยุด'
assert NEW not in s, 'แก้ไปแล้ว'
d['brain']['mn']['sys'] = s.replace(OLD, NEW)

P.write_text(json.dumps(d, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
print('patched +%d ตัวอักษร' % (len(NEW) - len(OLD)))
lk = d['lookups']
for sec in ('10', '20', '30', '40', '50', '60'):
    n = len(d['brain']['mn']['sys']) + len(lk['lenSys'][sec]) + len(lk['lenOut'][sec]) + len(lk['lenVo'][sec])
    print(f'  systemInstruction {sec} วิ ≈ {n:,} ตัวอักษร')
