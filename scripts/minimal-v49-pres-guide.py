# ── ตัวเลือกใน UI ต้องตรงกับตาราง (ครบทุกตัวที่ไม่ว่าง)
found = []
def walk(x):
    if isinstance(x, dict):
        if x.get('field') == 'svPres1' and isinstance(x.get('options'), list): found.append(x)
        for v in x.values(): walk(v)
    elif isinstance(x, list):
        for v in x: walk(v)
walk(cfg['phases'])
assert len(found) == 1
vals = {o['value'] for o in found[0]['options'] if o['value']}
assert vals == set(GUIDE), ('ตารางไม่ตรงตัวเลือก', vals ^ set(GUIDE))
assert all('{' not in g for g in GUIDE.values())

mn = next(o for o in cfg['ops'] if o['id'] == 'mnPlan')
ps = mn['prompt']['parts'][0]['parts']
blk = ps[12]
assert blk.get('op') == 'block'
part = blk['parts'][0]
if isinstance(part['value'], dict) and cfg['lookups'].get('presGuide') == GUIDE:
    print('✓ แพตช์แล้ว (v49)'); sys.exit(0)
assert part['value'] == OLD_LINE, part['value']
part['value'] = {'op': 'concat', 'parts': [NEW_LINE,
                 {'op': 'lookup', 'table': 'presGuide', 'key': '{values.svPres1}', 'fallback': ''}, '\n']}
cfg['lookups']['presGuide'] = GUIDE

# ── ยาม: ส่วนอื่นไม่ขยับ
