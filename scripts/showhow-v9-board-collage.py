#!/usr/bin/env python3
# showhow-v9-board-collage.py — บอร์ดแบบ "คอลลาจภาพล้วน" (ไม่มีคอลัมน์ข้อความ) ทับ prompt ของ mnBoard..mnBoard6
# ที่มา: พี่หมีเสนอ 2026-09-20 หลังเห็นบอร์ดตัวอย่างแบบภาพล้วน 5 ช่อง มีแค่เลขกำกับ
# เหตุผล: ① บอร์ด = ภาพอ้างอิงให้โมเดลวิดีโอ ซึ่งได้คำบรรยายเป็นข้อความของตัวเองอยู่แล้ว ⇒ ตัวหนังสือบนบอร์ดแทบไม่เพิ่มข้อมูล
#          ② คอลัมน์ข้อความกินความกว้าง ~40% ⇒ ตัดออก = ภาพต่อฉากใหญ่ขึ้นเกือบเท่าตัว (สำคัญกับคลิปยาวหลายช่วง)
#          ③ ความพังทั้งตระกูลที่ไล่แก้มา v8.1-8.8 (หัวคอลัมน์อังกฤษ · ไทยสะกดเพี้ยน · ตารางพัง · หัวเรื่องงอก) อยู่ที่ส่วนข้อความทั้งหมด
# กติกาที่ยังต้องมีเหมือนเดิม: เลขกำกับฉาก · ช่องเท่ากันเรียงบนลงล่าง · ล็อกสินค้า/สถานที่ · โหมดคน · แสงจากบท · ข้อความบนภาพตามโหมด
# ใช้:  git show 875efd7~1:showhow-dev.json > showhow-dev.json && python3 scripts/showhow-v9-board-collage.py
import json, os
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'showhow-dev.json')
raw = open(P, encoding='utf-8').read(); d = json.loads(raw)

def eq(a, b): return {'op': 'eq', 'a': a, 'b': b}
def neq(a, b): return {'op': 'not', 'a': eq(a, b)}
def AND(*xs): return {'op': 'and', 'list': list(xs)}
def block(*pairs): return {'op': 'block', 'sep': '', 'parts': [{'when': w, 'value': v} for w, v in pairs]}
SUB, TITLE, NOTEXT = 'ซับไตเติ้ลรายฉาก', 'หัวเรื่องตอนเปิด', 'ไม่มีข้อความ'
VO_ON = AND(neq('{values.svAudio}', 'ไม่มีเสียงพากย์'), neq('{values.svAudio}', 'ASMR'))


def prompt_for(k):
    first, last = 5 * (k - 1) + 1, 5 * k
    parts = ['แผ่นภาพสตอรีบอร์ดแนวตั้ง ภาพล้วน ไม่มีตารางข้อความ ของคลิป "ทำให้ดู" เรื่อง "{item.productName}"']
    if k == 1:
        parts.append(block(('values.svSec>10', ' · ช่วงที่ 1 — ฉาก 1 ถึง 5')))
    else:
        parts.append(f' · ช่วงที่ {k} — ฉาก {first} ถึง {last}')
    # 🔑 ทรงช่องต้องใกล้เฟรมคลิป (9:16 แนวตั้ง) ไม่ใช่แถบนอน 2.8:1 — ช่องนอนทำให้โมเดลวิดีโอจัดองค์ประกอบแบบแนวนอนแล้วต้องบีบเข้าเฟรมตั้ง (พี่หมีทัก 2026-09-20)
    parts.append(' (บรรทัดนี้เป็นข้อมูลกำกับ ห้ามพิมพ์ลงบนภาพ)'
                 f'\nบังคับเลย์เอาต์: ตาราง 2 คอลัมน์ ช่องละ 1 ฉาก เรียงซ้าย→ขวา แล้วลงแถวถัดไป ครบ {first}-{last}'
                 f' · ฉาก {first} ถึง {last - 1} อยู่ในช่องทรงตั้ง (สูงกว่ากว้าง ราว 3:4) ขนาดเท่ากันทุกช่อง · ฉาก {last} เป็นช่องเดียวกินเต็มความกว้างที่แถวล่างสุด'
                 ' · ช่องติดกันสนิท ไม่มีเส้นคั่น ไม่มีช่องว่างสีขาวระหว่างช่อง และไม่มีขอบสีขาวรอบแผ่น — ภาพเต็มแผ่นจรดขอบทั้งสี่ด้าน · มุมช่องเป็นมุมฉาก ไม่มนมุม'
                 ' · มุมซ้ายบนของทุกช่องมีวงกลมทึบเล็ก ๆ ใส่เลขฉากอารบิกตัวเดียว · ห้ามมีคอลัมน์ข้อความ ห้ามมีคำบรรยายใต้ภาพ ห้ามมีหัวเรื่อง ห้ามมีกรอบแท็บเล็ต/มือถือ/กระดาษรอบนอก'
                 '\nภาพทุกช่อง: ภาพถ่ายสมจริงสไตล์สารคดีในบ้าน แสง {item.palette} · ระยะภาพตรงตามมุมกล้องของฉากนั้น (มุมกว้าง = เห็นทั้งพื้นที่) · ทุกช่องสถานที่เดียวกัน ของที่งานไม่ได้แตะคงที่'
                 '\nบอร์ดช่วงก่อนหน้าที่แนบมา (รูปท้าย ๆ): เป็นคลิปเดียวกัน — สถานที่ ของในฉาก เสื้อผ้าและถุงมือของคนทำ โทนแสง ต้องต่อจากนั้น และวางช่องติดกันสนิทไม่มีขอบขาวเหมือนกัน แต่ห้ามลอกภาพในช่อง')
    # v10: ช่วงที่มีฉากสุดท้ายของคลิป (svSec = 10k) ต้องปิดด้วยภาพกว้างมุมเดียวกับฉากแรก ⇒ ยึดบอร์ดช่วงแรกที่แนบมาเป็นต้นแบบมุมกล้อง
    parts.append(block((f'values.svSec={10 * k}',
                        f'\nช่องฉาก {last} = ฉากปิดของคลิป ต้องเป็นภาพกว้างเห็นทั้งพื้นที่ จุดยืนกล้อง ความสูง ทิศทาง และกรอบภาพเดียวกับฉากเปิดของคลิป'
                        + (' (ดูช่องแรกของแผ่นนี้)' if k == 1 else ' (ช่องแรกของบอร์ดช่วงที่ 1 ที่แนบมา = ต้นแบบมุมกล้อง ลอกกรอบภาพนั้นมาเลย) ห้ามเปลี่ยนสถานที่หรือมุม') + ' เปลี่ยนได้เฉพาะสภาพพื้นที่ที่ทำเสร็จแล้ว')))
    parts.append(block(({'op': 'refsFilled', 'key': 'prod', 'from': 'products', 'slot': 'image'},
                        '\nสินค้า = ของจริงตามรูปที่แนบ (หลายชิ้น = ชิ้นละรูป): ห้ามเปลี่ยนสี ทรง สัดส่วน ฉลาก โลโก้ จำนวน ห้ามวาดใหม่หรือเป็นการ์ตูน · มุมที่รูปไม่มีให้ใช้มุมใกล้สุด · เอาเฉพาะตัวสินค้า ห้ามลอกฉากหลัง ของประกอบ หรือข้อความโฆษณาจากรูป')))
    parts.append(block(({'op': 'refsFilled', 'key': 'prod', 'from': 'products', 'slot': 'room1'},
                        '\nสถานที่ = ห้องตามรูปที่แนบ (ผนัง พื้น เฟอร์นิเจอร์ หน้าต่าง ทิศแสง) เปลี่ยนได้เฉพาะผลของงาน · ช่องแรก = สภาพตามรูป')))
    parts.append('\nคน: ')
    parts.append({'op': 'lookup', 'table': 'charBoard', 'key': '{values.svChar}|{values.svCharSrc}', 'fallback': ''})
    COLOR = ' · หัวข้อตัวอักษรสีเข้มที่เข้ากับโทนสีของคลิป'   # ★ยาม dry-run-minimal ของ starter เช็ควลีนี้ ห้ามตัด
    title_txt = 'เฉพาะช่องแรกตามข้อความที่บทให้ (หัวเรื่อง) บรรทัดเดียว ฟอนต์ {values.svText}' + COLOR + ' · ช่องอื่นภาพล้วน' if k == 1 else 'ไม่มี — ภาพล้วนทุกช่อง'
    parts.append('\nตัวหนังสือบนภาพ: ')
    parts.append(block((f'values.svTextOn={SUB}', 'ใช้ข้อความที่บทให้ไว้ของช่องนั้นเท่านั้น (ช่องไหนไม่มี = ภาพล้วน ห้ามแต่งเอง) บรรทัดเดียว ฟอนต์ {values.svText}' + COLOR + ' ไม่ทับจุดที่กำลังทำ'),
                       (f'values.svTextOn={TITLE}', title_txt),
                       (f'values.svTextOn={NOTEXT}', 'ไม่มี — ภาพล้วนทุกช่อง (ยกเว้นฉลากจริงบนสินค้า)')))
    parts.append(' · นอกจากนี้ห้ามพิมพ์ตัวหนังสือใด ๆ ลงบนแผ่น ทั้งภาษาไทยและอังกฤษ ชื่อสไตล์ แบรนด์ที่ไม่ได้แนบ หรือ emoji'
                 '\n\nช่องภาพเรียงตามลำดับ (เลขในวงกลม = เลขหน้าบรรทัด):')
    for n in range(first, last + 1):
        parts.append({'op': 'concat', 'parts': [f'\n{n}. ' + '{item.s%dth} · มุมกล้อง: {item.cam%d}' % (n, n)]})
        ov_mode = eq('{values.svTextOn}', SUB) if not (k == 1 and n == 1) else neq('{values.svTextOn}', NOTEXT)
        parts.append(block((AND(ov_mode, neq('{item.ov%d}' % n, '')), ' · ข้อความ: "{item.ov%d}"' % n)))
    return {'op': 'concat', 'parts': parts}


boards = {}
def walk(n):
    if isinstance(n, dict):
        if str(n.get('id', '')).startswith('mnBoard') and n.get('type') == 'image': boards[n['id']] = n
        for v in n.values(): walk(v)
    elif isinstance(n, list):
        for v in n: walk(v)
walk(d)
assert sorted(boards) == ['mnBoard'] + [f'mnBoard{k}' for k in range(2, 7)], sorted(boards)
for k in range(1, 7):
    boards['mnBoard' if k == 1 else f'mnBoard{k}']['prompt'] = prompt_for(k)
open(P, 'w', encoding='utf-8').write(json.dumps(d, ensure_ascii=False, indent=1) + ('\n' if raw.endswith('\n') else ''))
print('✓ v9 board-collage · เขียน prompt ใหม่ 6 บอร์ด ·', os.path.getsize(P), 'bytes')
