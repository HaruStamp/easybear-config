#   ⇒ ฉาก 17/18/19 = **ภาพนิ่งล้วน ไม่มีใครทำอะไร** ⇒ วิดีโอไม่มีอะไรให้ขยับ 8 วินาที
#   ผลจริง: t=2.4 วิ มีวงกลมเลข "17" ติดมา · t=8.6 วิ ทั้งเฟรมกลายเป็น **คอลัมน์ช่องบอร์ด 16/18/20**
#   (ยืนยันว่าไม่ใช่ prompt ถูกตัด: clampWarnings = [] · บรรทัด Negative ยังอยู่ครบ)
#
# 🪤 กฎเดิมมีช่องโหว่พอดีกับเคสนี้: เขียนว่า "ห้ามช่วงใดเป็นโคลสอัพ**สินค้าหรือมือ**ล้วนครบทั้ง 5 ฉาก"
#    ฉาก 17-19 เป็นโคลสอัพ "พื้นผิวที่สะอาดแล้ว" (ไม่ใช่สินค้า ไม่ใช่มือ) และฉาก 20 เป็นภาพกว้าง
#    ⇒ LLM ทำตามกฎทุกตัวอักษรแล้วยังได้ช่วงที่พัง
import json, sys

P = sys.argv[1] if len(sys.argv) > 1 else 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))
sys_txt = c['brain']['mn']['sys']

OLD = ('- ทุกช่วง 10 วินาที (5 ฉากติดกัน) ต้องมีอย่างน้อย 2 ฉากที่เห็นพื้นที่จริงเป็นฉากหลัง '
       '(ภาพกว้างหรือปานกลาง) — ห้ามมีช่วงใดเป็นโคลสอัพสินค้าหรือมือล้วนครบทั้ง 5 ฉาก')
NEW = ('- ทุกช่วง 10 วินาที (5 ฉากติดกัน) ต้องมีอย่างน้อย 2 ฉากที่เห็นพื้นที่จริงเป็นฉากหลัง '
       '(ภาพกว้างหรือปานกลาง) — ห้ามมีช่วงใดเป็นโคลสอัพล้วนครบทั้ง 5 ฉาก '
       'นับโคลสอัพทุกชนิด ทั้งสินค้า มือ พื้นผิว และของที่สะอาด/เสร็จแล้ว\n'
       '- ทุกฉากต้องมีสิ่งที่กำลังเกิดขึ้นในเฟรม (มือกำลังลงมือ · น้ำ ฟอง ผ้า กำลังเคลื่อน · '
       'ของกำลังถูกวาง เปิด ยก เช็ด) — ฉากที่เป็นภาพนิ่งของผลลัพธ์ล้วน คือของที่สะอาดหรือเสร็จแล้ว '
       'โดยไม่มีใครทำอะไร มีได้ช่วงละไม่เกิน 1 ฉาก และต้องเป็นฉากสุดท้ายของช่วงนั้น '
       'ช่วงที่มีภาพนิ่งติดกัน 3 ฉากขึ้นไป โมเดลวิดีโอจะไม่มีอะไรให้ขยับ '
       'แล้วหันไปวาดแผ่นสตอรีบอร์ดเป็นแกลเลอรีภาพนิ่งแทน')

assert OLD in sys_txt, 'หาประโยคเดิมไม่เจอ — โครงเปลี่ยน ให้ไปอ่านก่อนแก้'
assert 'สิ่งที่กำลังเกิดขึ้นในเฟรม' not in sys_txt, 'รันซ้ำ'
c['brain']['mn']['sys'] = sys_txt.replace(OLD, NEW, 1)

n_old, n_new = len(sys_txt), len(c['brain']['mn']['sys'])
json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(f'v74 ok · brain.mn.sys {n_old} → {n_new} ตัวอักษร (+{n_new - n_old})')
