#!/usr/bin/env python3
# showhow v63 — ไทม์แลปส์ต้องล็อกกรอบใน s*en ด้วย ไม่ใช่แค่ camN
#
# หลักฐาน (ทาสีห้อง 20 วิ · arc=ไทม์แลปส์ · มุมกล้องอัตโนมัติ · บน v62):
#   camN = "ตั้งนิ่งมุมกว้าง" 10/10 ✓  แต่ **คลิปจริงยังเป็นโคลสอัพสลับไปมา**
#   เพราะ s*en เขียนว่า "Hands sticking masking tape…" / "Hand pouring paint…" = สั่งโคลสอัพ
#   และ prompt วิดีโอไม่มีบรรทัด CAMERA MODE (ผูกกับ svCamMode ซึ่งว่าง)
# ⇒ โมเดลวิดีโออ่าน s*en เป็นหลัก · ล็อกที่ camN อย่างเดียวไม่พอ
#
# v63: arcPlan ของไทม์แลปส์ สั่งให้ **ทุก s*en ขึ้นต้นด้วยวลีกรอบเดียวกันเป๊ะ** แล้วค่อยบอกสิ่งที่เปลี่ยน
#      (อยู่ใน systemInstruction ของ mnPlan = ไม่กินเพดาน prompt ภาพ/วิดีโอ)
#      🪤 ไม่ไปเติมบรรทัด CAMERA MODE ใน prompt วิดีโอ เพราะ headroom p95 เหลือ 3 ตัวอักษร
#         และตัววัด G9 ไม่ได้ไล่ค่า arc ⇒ เติมไปจะเกินเพดานแบบที่ยามมองไม่เห็น
import json, sys

P = sys.argv[1] if len(sys.argv) > 1 else 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))
ARC = 'ไทม์แลปส์กล้องนิ่ง'
ap = c['lookups']['arcPlan']
old = ap[ARC]
assert 'ขึ้นต้น s*en ว่า "Same wide shot"' in old, 'ข้อความ v60 เปลี่ยนไปแล้ว — หยุด'

ap[ARC] = ('โครงเรื่องที่ผู้ใช้เลือก: ไทม์แลปส์กล้องนิ่ง — กล้องตั้งนิ่งมุมเดียวทั้งคลิป '
           '🔴 **s1en ถึง s15en ทุกฉากต้องขึ้นต้นด้วยวลีเดียวกันเป๊ะ** ว่า "Same locked wide shot of <ชื่อพื้นที่>, " '
           'แล้วจึงบอกว่าในเฟรมเปลี่ยนไปแค่ไหน — ห้ามเขียนคำว่า close-up / macro / pan / zoom / tilt / handheld / over-the-shoulder ในฉากไหนเลย '
           'และห้ามบรรยายว่ากล้องขยับหรือเข้าใกล้ · camN ทุกฉาก = "ตั้งนิ่งมุมกว้าง" · '
           'ฉากติดกันห่างกันแค่ **ขั้นเดียว** ของงาน ห้ามข้ามขั้น · สิ่งที่ทำไปแล้วต้องสะสมค้างอยู่ในเฟรมทุกฉากถัดไป · '
           'ฉากสุดท้าย = กรอบเดียวกับฉากแรก เห็นผลลัพธ์เต็มพื้นที่ · เหมาะกับงานที่พื้นที่ค่อย ๆ เปลี่ยนทั้งผืน เช่น สร้าง/ต่อเติม/จัดสวน/ทาสี')

json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(f'v63 ok · arcPlan[ไทม์แลปส์] {len(old)} → {len(ap[ARC])} ตัวอักษร')
