#!/usr/bin/env python3
# showhow v59 — 3 อาการจากเคส "ไทม์แลปส์สร้างบ้าน 30 วิ" ที่พี่หมีทดสอบเอง (2026-09-22 19:00)
#
# ① วิดีโอกล้องนิ่งแต่ "ตัดข้ามขั้น" ไม่เนียนแบบไทม์แลปส์จริง (ฉาก 2 ถางหญ้ายังไม่เสร็จ → ฉาก 3 ดินโล่งแล้ว)
# ② บอร์ดช่วง 3 หลุดไปคนละที่/คนละหลัง (ช่วง 2 ยังเป็นผนังอิฐชั้นเดียว → ช่วง 3 เป็นบ้าน 2 ชั้นเสร็จแล้ว)
# ③ 🔴 **ทั้งช่วง 20-30 วิ คือแผ่นบอร์ดที่ถูกทำให้ขยับ** (เห็นช่องเลข ⑪⑫⑬⑭ เต็มจอตลอด 10 วินาที)
#
# 🔑 รากของ ③ ที่เพิ่งเห็นชัดจากเคสนี้: งานนี้ **ไม่มีรูปสินค้า/รูปห้องเลย**
#    ⇒ รูปอ้างอิงที่ส่งเข้าโมเดลวิดีโอ "เป็นแผ่นบอร์ดล้วน" และจำนวนไม่เท่ากันต่อช่วง:
#       ช่วง 1 = 1 แผ่น (ผ่าน) · ช่วง 2 = 2 แผ่น (ผ่าน) · **ช่วง 3+ = 3 แผ่น (พัง)**
#    ⇒ ยิ่งแผ่นเยอะ โมเดลยิ่งสรุปว่า "หน้าตาแบบแผ่นคือสิ่งที่ต้องวาด"
#    🪤 v58 ที่เพิ่งแก้ ทดสอบด้วยคลิป 10 วิ ช่วงเดียว = **ไม่เคยแตะเคส 3 แผ่นเลย** (ช่องโหว่ของวิธีทดสอบผม)
#
# แก้:
#   ① camVideoEN โหมดกล้องนิ่ง → เขียนใหม่เป็น "ไทม์แลปส์ต่อเนื่อง ห้ามตัดระหว่างขั้น" (ยาวเท่าเดิม)
#   ② brain.mn.sys (ไม่ถูกตัด) → งานก่อสร้าง/รีโนเวท ต้องล็อกทรงอาคารตั้งแต่ฉากโครงสร้างแรก
#   ③ mnVideo4/5/6 + mnVideo3 → **ตัดแผ่นหมุด (board ช่วง 1) ออก** เหลือ "แผ่นตัวเอง + แผ่นช่วงก่อนหน้า" = ทุกช่วง ≤2 แผ่น
#      (ความต่อเนื่องที่วิดีโอต้องใช้คือ "ช่วงก่อนหน้า" ส่วนหมุดช่วง 1 มีไว้ให้กฎฉากปิดของ *บอร์ด* ไม่ใช่ของวิดีโอ)
import json, sys

P = sys.argv[1] if len(sys.argv) > 1 else 'showhow-dev.json'
c = json.load(open(P, encoding='utf-8'))

# ③ ตัดแผ่นหมุดออกจาก mnVideo3-6
cut = []
for o in c['ops']:
    if not o['id'].startswith('mnVideo'):
        continue
    k = o['id'].replace('mnVideo', '') or '1'
    if int(k) < 3:
        continue
    also = o['refs']['also']
    before = len(also)
    o['refs']['also'] = [a for a in also if not (a.get('from') == 'tasks' and a.get('slot') == 'board')]
    assert len(o['refs']['also']) == before - 1, f'{o["id"]}: ไม่เจอแผ่นหมุดให้ตัด'
    sheets = [o['refs']['slot']] + [a['slot'] for a in o['refs']['also'] if a.get('from') == 'tasks']
    assert len(sheets) == 2, f'{o["id"]}: เหลือ {sheets}'
    cut.append(o['id'])
assert len(cut) == 4, cut

# ① โหมดกล้องนิ่ง = ไทม์แลปส์ต่อเนื่อง
cam = c['lookups']['camVideoEN']
OLD = 'CAMERA MODE: locked-off, one fixed wide framing for the whole clip so before/after compares directly; only the work changes inside the frame. '
NEW = 'CAMERA MODE: locked-off timelapse, one fixed wide framing all clip; work accumulates smoothly in frame, each stage grows out of the last, never cut. '
assert cam['ตั้งนิ่งเห็นทั้งพื้นที่'] == OLD, repr(cam['ตั้งนิ่งเห็นทั้งพื้นที่'])[:200]
cam['ตั้งนิ่งเห็นทั้งพื้นที่'] = NEW

# ② ล็อกทรงอาคารในบท (brain.mn.sys — ไม่ถูกตัด)
s = c['brain']['mn']['sys']
A = '- ห้ามย้อนสภาพ: ความคืบหน้าเดินหน้าอย่างเดียว ฉากหลังต้องเรียบร้อยกว่าฉากก่อนเสมอ'
ADD = ('\n- งานก่อสร้าง/ต่อเติม/รีโนเวท: ตั้งแต่ฉากที่เห็นโครงสร้างเป็นครั้งแรก ต้องระบุ **ทรงของอาคารให้ตายตัว** ใน s*en '
       '(จำนวนชั้น · ทรงหลังคา · ตำแหน่งบนที่ดินเทียบฉากแรก) แล้วทุกฉากหลังจากนั้นต้องเป็นหลังเดิมทรงเดิม — เปลี่ยนได้แค่ "ทำถึงขั้นไหนแล้ว"'
       '\n- กล้องนิ่งมุมเดิมทั้งคลิป: ฉากติดกันต้องห่างกันแค่ **ขั้นเดียว** ของงาน ห้ามข้ามขั้น (เช่น กำลังถางหญ้า → ถางเสร็จครึ่งแปลง ไม่ใช่กระโดดเป็นดินโล่งทั้งผืน)')
assert s.count(A) == 1 and 'ทรงของอาคารให้ตายตัว' not in s
c['brain']['mn']['sys'] = s.replace(A, A + ADD)

json.dump(c, open(P, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print(f'v59 ok · ตัดแผ่นหมุดจาก {cut} (เหลือช่วงละ 2 แผ่น) · camVideoEN {len(OLD)}→{len(NEW)} · brain.mn.sys +{len(ADD)}')
